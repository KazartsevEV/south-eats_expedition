def find(n):
    if isinstance(n,dict):
        if n.get("name")=="Tad Saleuy Waterfall": return n
        for v in n.values():
            x=find(v)
            if x is not None:return x
    elif isinstance(n,list):
        for v in n:
            x=find(v)
            if x is not None:return x
    return None

