def find_object(node, name):
    if isinstance(node, dict):
        if node.get("name") == name:
            return node
        for value in node.values():
            found = find_object(value, name)
            if found is not None:
                return found
    elif isinstance(node, list):
        for value in node:
            found = find_object(value, name)
            if found is not None:
                return found
    return None

def section_map(obj):
    sections = (((obj.get("traveler_card") or {}).get("annotation") or {}).get("sections") or [])
    return {row.get("section_id"): row for row in sections if isinstance(row, dict) and row.get("section_id")}

